'use strict';
const assert=require('node:assert/strict');
const {hash,cp}=require('./r5k_source_span_edit.cjs');
const {schema,canonical,digest,admit,screenWithAdmission}=require('./r5l_evidence_bridge.cjs');
const source='서쪽 유리창은 열려 있었다. 동쪽 유리창은 잠겨 있었다.';
const span=(s,term,kind)=>{const i=cp(s).join('').indexOf(term);return {kind,startCp:i,endCp:i+cp(term).length,sha256:hash(term)};};
const second=source.lastIndexOf('유리창');
const evidence={schema,sourceSha256:hash(source),coordinateUnit:'UNICODE_CODEPOINT',sourceFactIds:['WEST','EAST'],protectedSpans:[span(source,'잠겨 있었다','POLARITY')],mentions:[{startCp:second,endCp:second+3,text:'유리창'}]};
const pinned={sourceSha256:hash(source),evidenceSha256:digest(canonical(evidence))};
const run=(e=evidence,p=pinned,s=source)=>admit({evidence:e,pinned:p,source:s});
assert.equal(run().status,'PINNED_BYTE_EVIDENCE_ONLY');
assert.equal(run().semanticStatus,'UNVERIFIED');
assert.equal(run(evidence,pinned,source+'!').reason,'SOURCE_DIGEST_MISMATCH');
assert.equal(run({...evidence,sourceFactIds:['FORGED']}).reason,'EVIDENCE_DIGEST_MISMATCH');
assert.equal(run({...evidence,sourceFactIds:['FORGED']},{...pinned,evidenceSha256:digest(canonical({...evidence,sourceFactIds:['FORGED']}))}).status,'PINNED_BYTE_EVIDENCE_ONLY'); // replacement of independently pinned root is beyond this verifier
assert.equal(run(evidence,{...pinned,evidenceSha256:undefined}).reason,'MISSING_PINNED_ROOT');
assert.equal(run({...evidence,coordinateUnit:'UTF16'},{...pinned,evidenceSha256:digest(canonical({...evidence,coordinateUnit:'UTF16'}))}).reason,'SCHEMA_OR_COORDINATE_MISMATCH');
const bad={...evidence,protectedSpans:[{...evidence.protectedSpans[0],sha256:hash('열려 있었다')}]};
assert.equal(run(bad,{...pinned,evidenceSha256:digest(canonical(bad))}).reason,'INVALID_PROTECTED_SPAN');
const p={operation:'DELETE_REPEATED_NOMINAL',startCp:second,endCp:second+3,expected:'유리창',replacement:''};
const a=run();
const candidate=screenWithAdmission({admission:a,proposal:p,actorId:'NARRATOR',objectId:'WINDOW_1'});
assert.equal(candidate.status,'STRUCTURAL_CANDIDATE_ONLY');
assert.equal(candidate.semanticStatus,'UNVERIFIED');
assert.equal(candidate.naturalnessStatus,'UNVERIFIED');
assert.equal(screenWithAdmission({admission:a,proposal:{...p,startCp:0},actorId:'A',objectId:'B'}).reason,'EDIT_MENTION_NOT_WITNESSED');
assert.equal(screenWithAdmission({admission:run({...evidence,sourceFactIds:['FORGED']}),proposal:p,actorId:'A',objectId:'B'}).reason,'NOT_ADMITTED');
assert.throws(()=>canonical({bad:undefined}));
assert.equal(digest(canonical({b:2,a:1})),digest(canonical({a:1,b:2})));
console.log('R5l 15 tests pass; pinned digest is NOT proof of authenticity or coreference.');
